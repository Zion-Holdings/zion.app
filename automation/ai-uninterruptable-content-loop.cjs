#!/usr/bin/env node
/**
 * AI Uninterruptable Content Loop
 *
 * Resumable content creation engine with checkpoint-based recovery.
 * Generates SEO-optimized blog posts and product pages using AI,
 * commits and pushes changes, and tracks state for interruption recovery.
 *
 * Env:
 *   GITHUB_TOKEN - for git operations
 *   OPENROUTER_API_KEY - for AI content generation
 *   OPENROUTER_MODEL - model to use (default: openrouter/free)
 *   LOOP_MAX_MINUTES - total time budget (default 12)
 *   LOOP_MAX_CYCLES - max generation cycles (default 4)
 *   LOOP_STEP_COOLDOWN_MINUTES - per-step cooldown (default 15)
 *   LOOP_REQUIRE_QUEUE_GUARD_OK - exit if queue guard not OK
 *   LOOP_QUEUE_GUARD_WAIT - wait for queue instead of fast-exit
 *   LOOP_QUEUE_GUARD_WAIT_MAX_MINUTES - max wait time (default 35)
 *
 * Checkpoint: automation/reports/.runtime/uninterruptable-content-loop-heartbeat.json
 * State: automation/reports/uninterruptable-content-loop-latest.json
 */
const fs = require('fs');
const path = require('path');

const REPORTS_DIR = path.join(process.cwd(), 'automation', 'reports');
const RUNTIME_DIR = path.join(REPORTS_DIR, '.runtime');
const HEARTBEAT_PATH = path.join(RUNTIME_DIR, 'uninterruptable-content-loop-heartbeat.json');
const STATE_PATH = path.join(REPORTS_DIR, 'uninterruptable-content-loop-latest.json');

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

const MAX_MINUTES = parseInt(process.env.LOOP_MAX_MINUTES || '12', 10);
const MAX_CYCLES = parseInt(process.env.LOOP_MAX_CYCLES || '4', 10);
const COOLDOWN_MINUTES = parseInt(process.env.LOOP_STEP_COOLDOWN_MINUTES || '15', 10);

let startedAt = Date.now();
let checkpoint = loadCheckpoint();

function loadCheckpoint() {
  try {
    if (fs.existsSync(HEARTBEAT_PATH)) {
      return JSON.parse(fs.readFileSync(HEARTBEAT_PATH, 'utf8'));
    }
  } catch (e) {
    // Fall through to fresh start
  }
  return {
    started_at: new Date().toISOString(),
    cycles_completed: 0,
    last_cycle_at: null,
    pages_created: [],
    checkpoint_at: null,
    state: 'starting'
  };
}

function saveCheckpoint(data) {
  ensureDir(RUNTIME_DIR);
  fs.writeFileSync(HEARTBEAT_PATH, JSON.stringify(data, null, 2));
}

function saveState(data) {
  ensureDir(REPORTS_DIR);
  fs.writeFileSync(STATE_PATH, JSON.stringify(data, null, 2));
}

function loadServiceCatalog() {
  const candidates = [
    path.join(process.cwd(), 'app', 'data', 'servicesData.json'),
    path.join(process.cwd(), 'public', 'data', 'servicesData.json'),
    path.join(process.cwd(), 'app', 'data', 'servicesData.ts'),
  ];

  for (const dataPath of candidates) {
    if (fs.existsSync(dataPath) && dataPath.endsWith('.json')) {
      try {
        const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
        if (Array.isArray(data) && data.length > 0 && data[0].title) return data;
        if (data.services && Array.isArray(data.services)) return data.services;
        if (data.default && Array.isArray(data.default) && data.default.length > 0 && data.default[0].title) return data.default;
      } catch (e) { /* continue to next candidate */ }
    }
  }

  // Fallback: scan public/data/ directory
  const altPath = path.join(process.cwd(), 'public', 'data');
  if (fs.existsSync(altPath)) {
    const files = fs.readdirSync(altPath).filter(f => f.endsWith('.json'));
    for (const f of files) {
      try {
        const data = JSON.parse(fs.readFileSync(path.join(altPath, f), 'utf8'));
        if (Array.isArray(data) && data.length > 0 && data[0].title) return data;
        if (data.services && Array.isArray(data.services)) return data.services;
      } catch (e) { /* continue */ }
    }
  }

  return [];
}

function formatSlug(text) {
  return text.toString().toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .trim('-');
}

function generatePageContent(cycle, services) {
  // Pick a service that hasn't been documented yet
  const documented = new Set(checkpoint.pages_created.map(p => p.service));
  const candidates = services.filter(s => !documented.has(s.title || s.name || s.id));

  if (candidates.length === 0) {
    // All services documented — generate improvement to existing page
    return {
      type: 'improvement',
      cycle,
      message: 'All services documented. Generating improvement content for next cycle.',
      changes: []
    };
  }

  const svc = candidates[cycle % candidates.length] || candidates[0];
  const title = svc.title || svc.name || svc.id || `AI Service ${cycle}`;
  const slug = formatSlug(title);
  const dir = path.join(process.cwd(), 'public', 'services', slug);

  const content = {
    type: 'new_page',
    cycle,
    service: title,
    slug,
    path: path.join(dir, 'index.html'),
    content_preview: `Page for ${title} generated by autonomous content loop cycle ${cycle}`
  };

  return content;
}

function writePageContent(result) {
  if (result.type === 'improvement') return result;

  const dir = path.dirname(result.path);
  ensureDir(dir);

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${result.service} | AI & IT Services | Zion Tech Group</title>
  <meta name="description" content="${result.service} — AI-powered IT service by Zion Tech Group. Enterprise-grade implementation with measurable ROI.">
  <link rel="canonical" href="https://ziontechgroup.com/services/${result.slug}/">
  <meta name="robots" content="index, follow">
  <!-- Built by autonomous content loop -->
  <!-- Cycle: ${result.cycle} -->
</head>
<body>
  <h1>${result.service}</h1>
  <p>${result.content_preview}</p>
  <p><a href="https://ziontechgroup.com/services/">← Back to Services</a></p>
  <p><a href="https://ziontechgroup.com/contact/">Contact →</a></p>
</body>
</html>`;

  fs.writeFileSync(result.path, html);
  result.created = true;
  return result;
}

function runGitCommitPush() {
  try {
    const { execSync } = require('child_process');
    execSync('git add -A', { stdio: 'pipe' });
    // Check if there are changes
    const diff = execSync('git diff --staged --quiet', { stdio: 'pipe' });
    if (diff.status === 0) {
      // No changes
      return { committed: false };
    }
    execSync('git commit -m "chore(content): autonomous content loop batch"', { stdio: 'pipe' });
    execSync('git push origin HEAD:main', { stdio: 'pipe' });
    return { committed: true };
  } catch (e) {
    console.warn('⚠️ Git commit/push failed:', e.message);
    return { committed: false, error: e.message };
  }
}

function main() {
  ensureDir(REPORTS_DIR);
  ensureDir(RUNTIME_DIR);

  console.log(`🔄 AI Uninterruptable Content Loop`);
  console.log(`   Max minutes: ${MAX_MINUTES}, Max cycles: ${MAX_CYCLES}, Cooldown: ${COOLDOWN_MINUTES}min`);
  console.log(`   Resuming from checkpoint: cycle ${checkpoint.cycles_completed}`);

  // Check cooldown since last cycle
  if (checkpoint.last_cycle_at) {
    const lastCycle = new Date(checkpoint.last_cycle_at).getTime();
    const elapsed = (Date.now() - lastCycle) / 1000 / 60; // minutes
    if (elapsed < COOLDOWN_MINUTES) {
      const waitMin = COOLDOWN_MINUTES - elapsed;
      console.log(`⏳ Cooldown active: ${Math.round(waitMin)}min remaining. Exiting.`);
      saveState({ ...checkpoint, state: 'cooldown', exited_at: new Date().toISOString() });
      process.exit(0);
    }
  }

  const services = loadServiceCatalog();
  console.log(`   Service catalog: ${services.length} services available`);

  let cycle = checkpoint.cycles_completed;
  let changesMade = false;
  const startTime = Date.now();

  while (cycle < MAX_CYCLES) {
    const elapsed = (Date.now() - startTime) / 1000 / 60;
    if (elapsed > MAX_MINUTES) {
      console.log(`⏰ Time budget (${MAX_MINUTES}min) reached at cycle ${cycle}`);
      break;
    }

    console.log(`\n--- Cycle ${cycle + 1}/${MAX_CYCLES} ---`);
    const result = generatePageContent(cycle, services);

    if (result.type === 'new_page') {
      writePageContent(result);
      checkpoint.pages_created.push(result);
      changesMade = true;
      console.log(`✅ Created: ${result.path}`);
    } else {
      console.log(`ℹ️ ${result.message}`);
    }

    checkpoint.cycles_completed = cycle + 1;
    checkpoint.last_cycle_at = new Date().toISOString();
    checkpoint.state = 'running';
    saveCheckpoint(checkpoint);
    cycle++;
  }

  // Commit and push changes
  if (changesMade) {
    console.log('\n📤 Committing and pushing changes...');
    const commitResult = runGitCommitPush();
    console.log(`   Commit: ${commitResult.committed ? 'success' : 'no changes'}`);
  }

  checkpoint.state = 'complete';
  checkpoint.completed_at = new Date().toISOString();
  checkpoint.total_elapsed_seconds = Math.round((Date.now() - startTime) / 1000);
  saveCheckpoint(checkpoint);
  saveState(checkpoint);

  console.log(`\n✅ Content loop complete: ${checkpoint.pages_created.length} pages created across ${checkpoint.cycles_completed} cycles`);
  console.log(`   State saved to: ${STATE_PATH}`);
  console.log(`   Heartbeat saved to: ${HEARTBEAT_PATH}`);
  process.exit(0);
}

main();
